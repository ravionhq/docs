// Generates one MDX page per standard-library module definition under
// module-definitions/catalog/, using `ravion` CLI output, and keeps the
// docs.json navigation group in sync.
//
// Usage: node scripts/sync-module-catalog.mjs
// Auth: uses your local `ravion login` session, or RAVION_API_KEY in CI.

import {execFileSync} from "node:child_process";
import {mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync} from "node:fs";
import path from "node:path";

const root = process.cwd();
const targetDir = path.join(root, "module-definitions/catalog");
const indexSnippetPath = path.join(root, "snippets/standard-library-index.mdx");
const docsJsonPath = path.join(root, "docs.json");
const banner =
  "{/* Generated by scripts/sync-module-catalog.mjs from the Ravion module catalog. Do not edit by hand. */}";

function ravion(args) {
  const stdout = execFileSync("ravion", args, {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return JSON.parse(stdout);
}

// Escape characters that MDX would treat as JSX/expressions, but leave
// fenced code blocks and inline code spans untouched.
function escapeMdx(markdown) {
  const lines = markdown.split("\n");
  let inFence = false;
  const out = lines.map((line) => {
    const trimmed = line.trimStart();
    if (trimmed.startsWith("```") || trimmed.startsWith("~~~")) {
      inFence = !inFence;
      return line;
    }
    if (inFence) return line;
    // Split on inline code spans; escape only outside them.
    return line
      .split(/(`+[^`]*`+)/)
      .map((part, i) =>
        i % 2 === 1 ? part : part.replace(/([{}<])/g, "\\$1"),
      )
      .join("");
  });
  return out.join("\n");
}

// Demote ATX headings by one level (## -> ###) so readme content nests under
// the page's own "## Readme" heading. Skips fenced code blocks.
function demoteHeadings(markdown) {
  const lines = markdown.split("\n");
  let inFence = false;
  return lines
    .map((line) => {
      const trimmed = line.trimStart();
      if (trimmed.startsWith("```") || trimmed.startsWith("~~~")) {
        inFence = !inFence;
        return line;
      }
      if (inFence) return line;
      return line.replace(/^(#{1,5})(\s)/, "#$1$2");
    })
    .join("\n");
}

function inlineCode(value) {
  const str = typeof value === "string" ? value : JSON.stringify(value);
  if (str === "") return "`\"\"`";
  return `\`${str.replace(/`/g, "\\`")}\``;
}

function renderInput(input, depth = 0) {
  const indent = "  ".repeat(depth);
  const lines = [];
  const attrs = [
    `name="${input.id}"`,
    `type="${input.type}"`,
    input.required ? "required" : null,
  ]
    .filter(Boolean)
    .join(" ");

  lines.push(`${indent}<ResponseField ${attrs}>`);

  const body = [];
  const label = input.label ? `**${escapeMdx(input.label)}.**` : null;
  const description = input.description ? escapeMdx(input.description) : null;
  body.push([label, description].filter(Boolean).join(" "));

  const facts = [];
  if (input.default !== undefined && input.default !== null && input.default !== "") {
    facts.push(`- Default: ${inlineCode(input.default)}`);
  }
  if (Array.isArray(input.values) && input.values.length > 0) {
    const opts = input.values
      .map((v) => {
        const value = inlineCode(v.value ?? v);
        return v.label && v.label !== v.value ? `${value} (${escapeMdx(v.label)})` : value;
      })
      .join(", ");
    facts.push(`- Allowed values: ${opts}`);
  }
  if (input.min !== undefined) facts.push(`- Min: ${inlineCode(input.min)}`);
  if (input.max !== undefined) facts.push(`- Max: ${inlineCode(input.max)}`);
  if (input.immutable) facts.push("- Immutable after creation");
  if (Array.isArray(input.patterns)) {
    for (const p of input.patterns) {
      facts.push(
        `- Pattern: ${inlineCode(p.pattern)}${p.message ? ` — ${escapeMdx(p.message)}` : ""}`,
      );
    }
  }
  if (input.show_when) {
    facts.push(`- Shown when: ${inlineCode(input.show_when)}`);
  }
  if (facts.length > 0) body.push(facts.join("\n"));

  for (const paragraph of body.filter(Boolean)) {
    lines.push(
      paragraph
        .split("\n")
        .map((l) => `${indent}  ${l}`)
        .join("\n"),
    );
    lines.push("");
  }
  if (lines[lines.length - 1] === "") lines.pop();

  const itemInputs = Array.isArray(input.item_inputs)
    ? input.item_inputs.filter((i) => typeof i === "object" && i !== null)
    : [];
  if (itemInputs.length > 0) {
    lines.push("");
    lines.push(`${indent}  <Expandable title="item fields">`);
    for (const child of itemInputs) {
      lines.push(renderInput(child, depth + 2));
    }
    lines.push(`${indent}  </Expandable>`);
  }

  lines.push(`${indent}</ResponseField>`);
  return lines.join("\n");
}

function renderInputs(inputs, pageTitle) {
  const sections = [];
  let current = {label: null, inputs: []};
  for (const input of inputs) {
    if (input.type === "section") {
      if (current.inputs.length > 0 || current.label) sections.push(current);
      current = {label: input.label ?? input.id, inputs: []};
    } else {
      current.inputs.push(input);
    }
  }
  if (current.inputs.length > 0 || current.label) sections.push(current);

  const parts = [];
  for (const section of sections) {
    if (section.label) {
      const label = headingSlug(section.label) === headingSlug(pageTitle) ? `${section.label} config` : section.label;
      parts.push(`### ${escapeMdx(label)}`);
    }
    for (const input of section.inputs) parts.push(renderInput(input));
  }
  return parts.join("\n\n");
}

function headingSlug(value) {
  return String(value)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9_\s-]/g, "")
    .replace(/\s+/g, "-");
}

function yamlString(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

// --- Module relationship graph ---------------------------------------------
// Dependencies between standard-library modules are encoded as inputs whose
// type is "$ref:<module-type>". We collect those (including refs nested in
// item_inputs) to build a graph of dependencies and downstream consumers.

function collectModuleRefs(inputs, refs = [], nested = false) {
  for (const input of inputs ?? []) {
    if (typeof input?.type === "string" && input.type.startsWith("$ref:")) {
      refs.push({
        target: input.type.slice("$ref:".length),
        inputId: input.id,
        // Refs nested inside list items or gated behind show_when are not
        // unconditionally required, so treat them as optional edges.
        optional: nested || !input.required || Boolean(input.show_when),
      });
    }
    if (Array.isArray(input?.item_inputs)) {
      collectModuleRefs(input.item_inputs, refs, true);
    }
  }
  return refs;
}

function buildRelationGraph(definitions, versionsByType) {
  const graph = new Map();
  for (const d of definitions) {
    graph.set(d.type, {deps: new Map(), consumers: new Map()});
  }
  for (const d of definitions) {
    const inputs = versionsByType.get(d.type)?.config?.inputs;
    for (const ref of collectModuleRefs(inputs)) {
      const deps = graph.get(d.type).deps;
      const existing = deps.get(ref.target);
      // Prefer the required edge if the same target is referenced twice.
      if (!existing || (existing.optional && !ref.optional)) {
        deps.set(ref.target, ref);
      }
    }
  }
  for (const [type, node] of graph) {
    for (const [target, ref] of node.deps) {
      graph.get(target)?.consumers.set(type, ref);
    }
  }
  return graph;
}

function mermaidId(type) {
  return type.replace(/[^A-Za-z0-9]/g, "_");
}

function renderRelationsDiagram(type, graph, currentLabel = type) {
  const node = graph.get(type);
  const deps = node?.deps ?? new Map();
  const consumers = node?.consumers ?? new Map();
  if (deps.size === 0 && consumers.size === 0) return null;

  const edges = [];
  const depNodes = new Set();
  const consumerNodes = new Set();
  const fadedNodes = new Set();

  for (const [consumer, ref] of [...consumers].sort(([a], [b]) => a.localeCompare(b))) {
    edges.push({from: consumer, to: type, optional: ref.optional, faded: false});
    consumerNodes.add(consumer);
  }
  for (const [target, ref] of deps) {
    edges.push({from: type, to: target, optional: ref.optional, faded: false});
    depNodes.add(target);
  }

  // Upstream dependencies of dependencies, rendered faded.
  const queue = [...deps.keys()];
  const expanded = new Set([type, ...deps.keys()]);
  while (queue.length > 0) {
    const current = queue.shift();
    for (const [target, ref] of graph.get(current)?.deps ?? new Map()) {
      edges.push({from: current, to: target, optional: ref.optional, faded: true});
      if (!depNodes.has(target) && !consumerNodes.has(target) && target !== type) {
        fadedNodes.add(target);
      }
      if (!expanded.has(target)) {
        expanded.add(target);
        queue.push(target);
      }
    }
  }

  const lines = ["```mermaid", "flowchart BT"];
  const declared = new Set();
  const declare = (t) => {
    if (declared.has(t)) return mermaidId(t);
    declared.add(t);
    const label = t === type ? `<strong>${currentLabel}</strong>` : t;
    return `${mermaidId(t)}["${label.replace(/"/g, "#quot;")}"]`;
  };

  const fadedEdgeIndexes = [];
  edges.forEach((edge, i) => {
    const arrow = edge.optional ? "-.->" : "-->";
    lines.push(`  ${declare(edge.from)} ${arrow} ${declare(edge.to)}`);
    if (edge.faded) fadedEdgeIndexes.push(i);
  });

  lines.push("");
  lines.push(`  class ${mermaidId(type)} current`);
  if (depNodes.size > 0) {
    lines.push(`  class ${[...depNodes].map(mermaidId).join(",")} dependency`);
  }
  if (consumerNodes.size > 0) {
    lines.push(`  class ${[...consumerNodes].map(mermaidId).join(",")} consumer`);
  }
  if (fadedNodes.size > 0) {
    lines.push(`  class ${[...fadedNodes].map(mermaidId).join(",")} upstream`);
  }

  lines.push("");
  lines.push("  classDef current fill:#C4B5FD,stroke:#8B5CF6,color:#3B0764");
  lines.push("  classDef dependency fill:#FAF8FF,stroke:#DDD6FE,color:#6D28D9");
  lines.push("  classDef consumer fill:#F3F4F6,stroke:#9CA3AF,color:#4B5563");
  lines.push("  classDef upstream fill:#F8FAFC,stroke:#CBD5E1,color:#94A3B8");
  if (fadedEdgeIndexes.length > 0) {
    lines.push(`  linkStyle ${fadedEdgeIndexes.join(",")} stroke:#CBD5E1,color:#94A3B8`);
  }

  lines.push("");
  for (const t of new Set([...consumerNodes, ...depNodes, ...fadedNodes])) {
    if (!graph.has(t)) continue;
    lines.push(`  click ${mermaidId(t)} "/module-definitions/catalog/${t}" "Open ${t} docs"`);
  }

  lines.push("```");
  return {diagram: lines.join("\n"), hasFaded: fadedNodes.size > 0};
}

function renderRelationsSection(definition, graph) {
  const rendered = renderRelationsDiagram(definition.type, graph, definition.name);
  if (!rendered) return null;
  return [
    "## Dependencies and consumers",
    "",
    rendered.diagram,
    "",
    "_Every dependency input can be specified manually to reference existing external infrastructure rather than a Ravion module. Set the dependency input to `null` and set its mapped inputs directly; see [Use existing infrastructure instead of a module reference](/config-as-code/project-config-file#use-existing-infrastructure-instead-of-a-module-reference)._",
  ].join("\n");
}

function renderPage(definition, version, graph) {
  const config = version.config ?? {};
  const readme = (config.readme ?? "").trim();
  const inputs = Array.isArray(config.inputs) ? config.inputs : [];

  const frontmatter = [
    "---",
    `title: ${yamlString(definition.name)}`,
    `sidebarTitle: ${yamlString(definition.type)}`,
    `description: ${yamlString(definition.description ?? "")}`,
    `keywords: [${yamlString(definition.type)}, ${yamlString(definition.name)}]`,
    "---",
  ].join("\n");

  const meta = [
    `**Type:** \`${definition.type}\``,
    `**Latest version:** \`${definition.latestVersion}\``,
  ].join(" · ");

  const sections = [frontmatter, "", banner, "", meta];

  const relations = renderRelationsSection(definition, graph);
  if (relations) {
    sections.push("", relations);
  }

  if (readme) {
    sections.push("", "## Readme", "", escapeMdx(demoteHeadings(readme)));
  }

  if (inputs.length > 0) {
    sections.push(
      "",
      "## Inputs reference",
      "",
      `All inputs for \`${definition.type}\` version \`${definition.latestVersion}\`. Use the \`name\` shown for each field as the input key in module config.`,
      "",
      renderInputs(inputs, definition.name),
    );
  }

  return `${sections.join("\n").trimEnd()}\n`;
}

function updateDocsJson(pageSlugs) {
  const docsJson = JSON.parse(readFileSync(docsJsonPath, "utf8"));
  const tabs = docsJson.navigation?.tabs ?? [];
  const docTab = tabs.find((t) => t.tab === "Documentation");
  const group = docTab?.groups?.find((g) => g.group === "Modules");
  if (!group) {
    throw new Error('Could not find "Modules" group in docs.json');
  }

  // Remove any existing "Standard library" entry wherever it lives.
  for (const g of docTab.groups) {
    g.pages = g.pages.filter(
      (p) => !(typeof p === "object" && p.group === "Standard library"),
    );
  }

  // Append at the bottom of the Modules group, with a clickable root page.
  group.pages.push({
    group: "Standard library",
    root: "module-definitions/standard-library",
    pages: pageSlugs,
  });

  writeFileSync(docsJsonPath, `${JSON.stringify(docsJson, null, 2)}\n`);
}

const definitions = ravion([
  "module",
  "definition",
  "list",
  "--status",
  "ACTIVE",
  "--include-latest-version",
  "--limit",
  "100",
  "--json",
]).filter((d) => d.type.startsWith("rvn-") && d.latestVersionId);

if (definitions.length === 0) {
  throw new Error("No active rvn-* module definitions returned; refusing to wipe catalog pages.");
}

definitions.sort((a, b) => a.type.localeCompare(b.type));

mkdirSync(targetDir, {recursive: true});

const generatedFiles = new Set();
const pageSlugs = [];

// Fetch every version first so the relationship graph can span the whole
// catalog before any page renders.
const versionsByType = new Map();
for (const definition of definitions) {
  versionsByType.set(
    definition.type,
    ravion(["module", "version", "get", definition.latestVersionId, "--json"]),
  );
}
const relationGraph = buildRelationGraph(definitions, versionsByType);

for (const definition of definitions) {
  const version = versionsByType.get(definition.type);
  const fileName = `${definition.type}.mdx`;
  writeFileSync(path.join(targetDir, fileName), renderPage(definition, version, relationGraph));
  generatedFiles.add(fileName);
  pageSlugs.push(`module-definitions/catalog/${definition.type}`);
  console.log(`generated ${fileName} (v${definition.latestVersion})`);
}

const indexCards = definitions
  .map((d) =>
    [
      `  <Card title=${yamlString(d.name)} href="/module-definitions/catalog/${d.type}">`,
      `    \`${d.type}\` · v${d.latestVersion}`,
      "",
      `    ${escapeMdx(d.description ?? "")}`,
      "  </Card>",
    ].join("\n"),
  )
  .join("\n");
writeFileSync(
  indexSnippetPath,
  `${banner}\n\n<Columns cols={2}>\n${indexCards}\n</Columns>\n`,
);
console.log("generated snippets/standard-library-index.mdx");

for (const file of readdirSync(targetDir)) {
  if (file.endsWith(".mdx") && !generatedFiles.has(file)) {
    rmSync(path.join(targetDir, file));
    console.log(`removed stale ${file}`);
  }
}

updateDocsJson(pageSlugs);
console.log(`updated docs.json with ${pageSlugs.length} catalog pages`);
