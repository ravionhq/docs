export function renderAnchorRedirectScript(docs) {
  return `// Generated by scripts/anchor-redirects.mjs. Do not edit.
(() => {
  const docs = ${JSON.stringify(docs)};
  const redirect = () => {
    let hash;
    try {
      hash = decodeURIComponent(location.hash.slice(1));
    } catch {
      return;
    }
    if (!hash) return;

    const pathname = location.pathname.replace(/\\/+$/, "") || "/";
    for (const doc of docs) {
      const page = doc.pages.find(
        (candidate) => pathname === candidate || pathname.endsWith(candidate),
      );
      if (!page) continue;

      const target = doc.anchors[hash];
      if (!target || target === page || document.getElementById(hash)) return;

      const prefix = pathname.slice(0, pathname.length - page.length);
      location.replace(prefix + target + "#" + hash);
      return;
    }
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", redirect, {once: true});
  } else {
    redirect();
  }
  addEventListener("hashchange", redirect);
})();
`;
}
