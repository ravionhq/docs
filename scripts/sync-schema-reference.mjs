const generatedBy = (name) =>
  `{/* Generated by scripts/sync-schema-reference.mjs from ../flightcontrol/packages/schemas/schema_reference/docs/${name}.md. Do not edit by hand. */}`;

function readSource(name) {
  return readFileSync(path.join(sourceDir, `${name}.md`), "utf8").trimEnd();
}

function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** Joins section titles into one sentence-case page title. */
function joinTitles(titles) {
  return titles
    .map((title, index) => (index === 0 ? title : `${title.charAt(0).toLowerCase()}${title.slice(1)}`))
    .join(", ");
}

function countFields(text) {
  return (text.match(/<ResponseField\b/g) ?? []).length;
}

/** Splits markdown into blocks introduced by a `##` or `###` heading. */
function parseBlocks(markdown) {
  const blocks = [];
  let current = null;

  for (const line of markdown.split("\n")) {
    const heading = /^(#{2,3}) (.+)$/.exec(line);
    if (heading) {
      current = {
        level: heading[1].length,
        title: heading[2].trim(),
        lines: [line],
      };
      blocks.push(current);
      continue;
    }
    if (current) {
      current.lines.push(line);
    }
  }

  return blocks.map((block) => {
    const text = block.lines.join("\n").trim();
    return {...block, text, fields: countFields(text)};
  });
}

/** Groups `###` blocks under the `##` block they belong to. */
function groupSections(blocks) {
  const sections = [];
  for (const block of blocks) {
    if (block.level === 2) {
      sections.push({title: block.title, intro: block, children: []});
      continue;
    }
    sections.at(-1)?.children.push(block);
  }
  return sections.map((section) => ({
    ...section,
    fields: section.intro.fields + section.children.reduce((sum, child) => sum + child.fields, 0),
  }));
}

/** Splits one oversized section into a page per configured group of types. */
function splitSection(section, groups) {
  if (!groups) {
    throw new Error(
      `Section "${section.title}" has ${section.fields} fields but no grouping rules; add an entry to sectionGroups.`,
    );
  }

  const pages = groups.map((group) => ({
    titles: [section.title],
    title: group.title,
    slug: slugify(group.title),
    blocks: [],
    fields: 0,
  }));
  const catchAllIndex = groups.findIndex((group) => !group.match);
  if (catchAllIndex === -1) {
    throw new Error(`Section "${section.title}" needs one group without a \`match\` rule.`);
  }

  for (const block of [section.intro, ...section.children]) {
    const index = groups.findIndex((group) => group.match?.test(block.title));
    const page = pages[index === -1 ? catchAllIndex : index];
    page.blocks.push(block);
    page.fields += block.fields;
  }

  const overflowing = pages.filter((page) => page.fields > maxFieldsPerPage);
  if (overflowing.length > 0) {
    const detail = overflowing.map((page) => `${page.title} (${page.fields})`).join(", ");
    throw new Error(
      `Grouped pages for "${section.title}" exceed ${maxFieldsPerPage} fields: ${detail}. Refine sectionGroups.`,
    );
  }

  return pages.filter((page) => page.blocks.length > 0);
}

/** Packs sections into pages that stay under the field budget. */
function buildPages(sections, config) {
  const pages = [];
  let current = null;

  for (const section of sections) {
    if (section.fields > maxFieldsPerPage) {
      current = null;
      pages.push(...splitSection(section, config.sectionGroups?.[section.title]));
      continue;
    }
    // Prose-only sections (no types of their own) ride along with the
    // previous page instead of becoming a near-empty sidebar entry.
    const packable =
      section.children.length === 0 && !config.standaloneSections?.includes(section.title);
    if (current && packable && current.fields + section.fields <= maxFieldsPerPage) {
      current.titles.push(section.title);
      current.blocks.push(section.intro, ...section.children);
      current.fields += section.fields;
      continue;
    }
    current = {
      titles: [section.title],
      blocks: [section.intro, ...section.children],
      fields: section.fields,
    };
    pages.push(current);
  }

  return pages.map((page) => {
    const slug = page.slug ?? slugify(page.titles[0]);
    return {
      ...page,
      slug,
      title: config.titleOverrides?.[slug] ?? page.title ?? joinTitles(page.titles),
    };
  });
}

/** Points same-document anchor links at the page that now holds the anchor. */
function rewriteAnchorLinks(text, pageSlug, anchorPages, pageDir) {
  return text.replace(/\]\(#([^)]+)\)/g, (match, anchor) => {
    const target = anchorPages.get(anchor);
    if (!target || target === pageSlug) {
      return match;
    }
    return `](/${pageDir}/${target}#${anchor})`;
  });
}

function syncSplitDoc(config) {
  const source = readSource(config.name);
  const blocks = parseBlocks(source);
  const preamble = blocks.filter((block) => block.level === 2 && block.title === "Legend");
  const sections = groupSections(blocks).filter((section) => section.title !== "Legend");
  const pages = buildPages(sections, config);

  const anchorPages = new Map();
  for (const page of pages) {
    for (const block of page.blocks) {
      anchorPages.set(slugify(block.title), page.slug);
    }
  }

  const partsDir = path.join(snippetDir, config.name);
  const pageDir = path.join(root, config.pageDir);
  for (const dir of [partsDir, pageDir]) {
    if (existsSync(dir)) {
      rmSync(dir, {recursive: true});
    }
    mkdirSync(dir, {recursive: true});
  }

  for (const page of pages) {
    const metadata = config.pageMetadata?.[page.slug];
    const title = metadata?.title ?? page.title;
    const sidebarTitle = metadata?.sidebarTitle ?? page.title;
    const description = metadata?.description ?? config.describe(page.titles);
    const body = [...preamble, ...page.blocks].map((block) => block.text).join("\n\n");
    writeFileSync(
      path.join(partsDir, `${page.slug}.mdx`),
      `${generatedBy(config.name)}\n\n${rewriteAnchorLinks(body, page.slug, anchorPages, config.pageDir)}\n`,
    );

    const componentName = `SchemaReferencePart`;
    writeFileSync(
      path.join(pageDir, `${page.slug}.mdx`),
      [
        "---",
        `title: ${JSON.stringify(title)}`,
        `sidebarTitle: ${JSON.stringify(sidebarTitle)}`,
        `description: ${JSON.stringify(description)}`,
        `boost: ${config.boost}`,
        `"og:image": "https://www.ravion.com/og/docs/${config.pageDir}/${page.slug}.png"`,
        `"twitter:image": "https://www.ravion.com/og/docs/${config.pageDir}/${page.slug}.png"`,
        "---",
        "",
        generatedBy(config.name),
        "",
        `import ${componentName} from "/snippets/schema-reference/${config.name}/${page.slug}.mdx";`,
        "",
        '<Visibility for="agents">',
        "  > The full rendered schema reference is omitted from this Markdown view to save tokens.",
        `  > Fetch [${config.compactSchemaUrl}](${config.compactSchemaUrl}) for the complete module definition schema in a compact, machine-readable format.`,
        "</Visibility>",
        "",
        '<Visibility for="humans">',
        `  <${componentName} />`,
        "</Visibility>",
        "",
      ].join("\n"),
    );
  }

  const index = pages
    .map((page) => `- [${page.title}](/${config.pageDir}/${page.slug})`)
    .join("\n");
  writeFileSync(
    path.join(root, config.indexSnippet),
    `${generatedBy(config.name)}\n\n${index}\n`,
  );

  updateNavigation(config, pages);
  console.log(
    `split ${config.name} schema reference into ${pages.length} pages under ${config.pageDir}/`,
  );
}

/** Replaces the reference page entry in docs.json with a group of split pages. */
function updateNavigation(config, pages) {
  const docsJson = JSON.parse(readFileSync(docsJsonPath, "utf8"));
  const rootPage = config.pageDir;
  const pagePaths = pages.map((page) => `${config.pageDir}/${page.slug}`);
  let replaced = false;

  const visit = (node) => {
    if (Array.isArray(node)) {
      node.forEach((entry, index) => {
        const isEntry =
          entry === rootPage || (entry !== null && typeof entry === "object" && entry.root === rootPage);
        if (isEntry) {
          node[index] = {
            group: typeof entry === "object" && entry.group ? entry.group : "Definition schema",
            root: rootPage,
            pages: pagePaths,
          };
          replaced = true;
          return;
        }
        visit(entry);
      });
      return;
    }
    if (node !== null && typeof node === "object") {
      Object.values(node).forEach(visit);
    }
  };

  visit(docsJson.navigation);

  if (!replaced) {
    throw new Error(`Could not find "${rootPage}" in the docs.json navigation.`);
  }

  writeFileSync(docsJsonPath, `${JSON.stringify(docsJson, null, 2)}\n`);
}

